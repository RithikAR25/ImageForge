#!/usr/bin/env node
/**
 * update-doc-index.mjs
 *
 * Automatically regenerates the "Document Statistics" section of
 * docs/DOCUMENT_INDEX.md to match the actual files on disk.
 *
 * Usage:
 *   node tools/scripts/update-doc-index.mjs
 *
 * Run this after adding, removing, or renaming any .md file.
 * It only updates the statistics block — all curated content is preserved.
 */

import { readdir, readFile, writeFile, stat } from 'node:fs/promises';
import { join, relative, extname, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, '..', '..');
const DOCS_ROOT = join(REPO_ROOT, 'docs');
const INDEX_FILE = join(DOCS_ROOT, 'DOCUMENT_INDEX.md');

// ─── Category detection ────────────────────────────────────────────────────

/**
 * Maps a docs-relative file path to a display category name.
 * @param {string} relPath - Path relative to docs/ directory
 * @returns {string} Category label
 */
function getCategory(relPath) {
  const parts = relPath.split('/');

  if (parts.length === 1) {
    const name = parts[0];
    if (['README.md', 'DOCUMENT_INDEX.md', 'GLOSSARY.md', 'DECISION_LOG.md', 'CHANGELOG.md'].includes(name)) {
      return 'Phase 0: Navigation Hub';
    }
    const num = parseInt(name, 10);
    if (num >= 1  && num <= 19)  return 'Phase 1: Product Planning';
    if (num >= 20 && num <= 49)  return 'Phase 2: Architecture';
    if (num >= 50 && num <= 59)  return 'Phase 3: UI/UX';
    if (num >= 70 && num <= 89)  return 'Phase 5: Tech Specs';
    return 'Other';
  }

  const dir = parts[0];
  const map = {
    'adr':          'ADR Folder',
    'features':     'Phase 4: Feature Modules',
    'performance':  'Phase 6: Performance',
    'security':     'Phase 7: Security',
    'quality':      'Phase 8: Quality',
    'deployment':   'Phase 9: Deployment',
    'future':       'Phase 10: Future',
    'api':          'API Documentation',
    'development':  'Development Guides',
    'benchmarks':   'Benchmarks',
    'ai':           'AI Development',
    'governance':   'Governance',
  };
  return map[dir] ?? 'Other';
}

// ─── File walker ───────────────────────────────────────────────────────────

/**
 * Recursively walks a directory and returns all .md file paths.
 * @param {string} dir
 * @param {string[]} [acc]
 * @returns {Promise<string[]>}
 */
async function walkMd(dir, acc = []) {
  const entries = await readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      await walkMd(full, acc);
    } else if (entry.isFile() && extname(entry.name) === '.md') {
      acc.push(full);
    }
  }
  return acc;
}

// ─── Stats builder ─────────────────────────────────────────────────────────

async function buildStats() {
  const allFiles = await walkMd(DOCS_ROOT);
  const counts = new Map();

  for (const file of allFiles) {
    const rel = relative(DOCS_ROOT, file).replace(/\\/g, '/');
    const category = getCategory(rel);
    counts.set(category, (counts.get(category) ?? 0) + 1);
  }

  const categoryOrder = [
    'Phase 0: Navigation Hub',
    'Phase 1: Product Planning',
    'Phase 2: Architecture',
    'ADR Folder',
    'Phase 3: UI/UX',
    'Phase 4: Feature Modules',
    'Phase 5: Tech Specs',
    'Phase 6: Performance',
    'Phase 7: Security',
    'Phase 8: Quality',
    'Phase 9: Deployment',
    'Phase 10: Future',
    'API Documentation',
    'Development Guides',
    'Benchmarks',
    'AI Development',
    'Governance',
    'Other',
  ];

  let total = 0;
  const rows = [];

  for (const cat of categoryOrder) {
    const count = counts.get(cat) ?? 0;
    if (count > 0) {
      rows.push(`| ${cat} | ${count} |`);
      total += count;
      counts.delete(cat);
    }
  }

  // Any remaining uncategorised
  for (const [cat, count] of counts) {
    rows.push(`| ${cat} | ${count} |`);
    total += count;
  }

  rows.push(`| **Total** | **${total}** |`);
  return { rows, total };
}

// ─── Index updater ─────────────────────────────────────────────────────────

const STATS_START = '## Document Statistics';
const STATS_TABLE_HEADER = '| Category | Count |';

async function updateIndex() {
  const content = await readFile(INDEX_FILE, 'utf8');
  const { rows, total } = await buildStats();

  const statsSection = [
    '## Document Statistics',
    '',
    `> Auto-generated by \`tools/scripts/update-doc-index.mjs\` — do not edit manually.`,
    '',
    '| Category | Count |',
    '|---|---|',
    ...rows,
    '',
    '---',
    '',
    `*Last updated: ${new Date().toISOString().slice(0, 10)} (auto) | Total: ${total} documents*`,
  ].join('\n');

  // Find and replace the existing Document Statistics section to end of file
  const statsIdx = content.indexOf(STATS_START);
  if (statsIdx === -1) {
    // Append if not found
    const updated = content.trimEnd() + '\n\n' + statsSection + '\n';
    await writeFile(INDEX_FILE, updated, 'utf8');
    console.log(`✅ Appended statistics section (${total} documents)`);
    return;
  }

  const before = content.slice(0, statsIdx);
  const updated = before + statsSection + '\n';
  await writeFile(INDEX_FILE, updated, 'utf8');

  console.log(`✅ Updated DOCUMENT_INDEX.md — ${total} documents indexed`);
}

// ─── Entry point ───────────────────────────────────────────────────────────

updateIndex().catch((err) => {
  console.error('❌ Failed to update document index:', err);
  process.exit(1);
});
